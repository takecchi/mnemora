import { describe, expect, it } from "vitest";
import { parsePgTimestamp } from "../mapping.js";

/**
 * 往復の歯（`timestamp-roundtrip.postgres.test.ts`）は本物の Postgres で、ミリ秒が3桁そろった7通りの日付だけを見る。ここは文字列を直接渡して、その外側を見る。
 * 年は `Date.UTC` でなく `setUTCFullYear` で入れる（0〜99年を1900年代に読まない）。小数秒は、ミリ秒より下を切り捨てる（四捨五入しない）。
 */

function iso(value: string | null): string | null {
  const date = parsePgTimestamp(value);
  return date === null ? null : date.toISOString();
}

describe("parsePgTimestamp: 時差つきの既定の出力を UTC の瞬間として読む", () => {
  const cases: [input: string, expected: string][] = [
    ["2026-05-11 00:47:17.621+09", "2026-05-10T15:47:17.621Z"],
    ["2026-01-01 00:00:00+00", "2026-01-01T00:00:00.000Z"],
    ["2026-01-01 00:00:00-05", "2026-01-01T05:00:00.000Z"],
    ["2026-01-01 00:00:00-03:30", "2026-01-01T03:30:00.000Z"],
    ["2026-01-01 12:00:00+09", "2026-01-01T03:00:00.000Z"],
    ["2026-01-01 12:00:00+0530", "2026-01-01T06:30:00.000Z"],
    ["1850-01-01 09:18:59+09:18:59", "1850-01-01T00:00:00.000Z"],
    ["1883-11-18 12:00:00-04:56:02", "1883-11-18T16:56:02.000Z"],
    ["2026-05-11T00:47:17.621+09:00", "2026-05-10T15:47:17.621Z"],
  ];
  for (const [input, expected] of cases) {
    it(`${input} → ${expected}`, () => {
      expect(iso(input)).toBe(expected);
    });
  }
});

describe("parsePgTimestamp: 小数秒はミリ秒より下を切り捨てる（桁数が足りなくても多くても）", () => {
  const cases: [input: string, expected: string][] = [
    ["2026-01-01 00:00:00.5+00", "2026-01-01T00:00:00.500Z"],
    ["2026-01-01 00:00:00.12+00", "2026-01-01T00:00:00.120Z"],
    ["2026-01-01 00:00:00.123+00", "2026-01-01T00:00:00.123Z"],
    ["2026-01-01 00:00:00.123456+00", "2026-01-01T00:00:00.123Z"],
    ["2026-01-01 00:00:00.999999+00", "2026-01-01T00:00:00.999Z"],
    ["2026-01-01 00:00:00.0005+00", "2026-01-01T00:00:00.000Z"],
    ["2026-01-01 00:00:00.001+00", "2026-01-01T00:00:00.001Z"],
    ["2026-01-01 00:00:00.123456+05:30", "2025-12-31T18:30:00.123Z"],
  ];
  for (const [input, expected] of cases) {
    it(`${input} → ${expected}`, () => {
      expect(iso(input)).toBe(expected);
    });
  }
});

describe("parsePgTimestamp: 年の読み方（西暦の小さい年・紀元前・5桁以上）", () => {
  const cases: [input: string, expected: string][] = [
    // `Date.UTC` は 0〜99 年を 1900 年代として読む——西暦1〜99年を1900年代にしない。
    ["0001-01-01 00:00:00+00", "0001-01-01T00:00:00.000Z"],
    ["0050-06-15 12:00:00+00", "0050-06-15T12:00:00.000Z"],
    ["0099-12-31 23:59:59+00", "0099-12-31T23:59:59.000Z"],
    ["0100-01-01 00:00:00+00", "0100-01-01T00:00:00.000Z"],
    ["0001-06-01 00:00:00+00 BC", "0000-06-01T00:00:00.000Z"],
    ["0002-06-01 00:00:00+00 BC", "-000001-06-01T00:00:00.000Z"],
    ["0101-03-01 00:00:00+00 BC", "-000100-03-01T00:00:00.000Z"],
    ["0001-06-01 09:00:00.250+09 BC", "0000-06-01T00:00:00.250Z"],
    ["10000-01-01 00:00:00+00", "+010000-01-01T00:00:00.000Z"],
    ["275760-09-13 00:00:00+00", "+275760-09-13T00:00:00.000Z"],
    ["275760-09-13 09:00:00+09", "+275760-09-13T00:00:00.000Z"],
  ];
  for (const [input, expected] of cases) {
    it(`${input} → ${expected}`, () => {
      expect(iso(input)).toBe(expected);
    });
  }

  it("null は null", () => {
    expect(parsePgTimestamp(null)).toBeNull();
  });
});
